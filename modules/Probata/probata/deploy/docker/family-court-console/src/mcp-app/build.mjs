function stripLegacyDarkMediaQueries(source) {
  const marker = "@media(prefers-color-scheme:dark)";
  let result = source;
  while (result.includes(marker)) {
    const start = result.indexOf(marker);
    const open = result.indexOf("{", start);
    let depth = 0;
    let end = open;
    for (; end < result.length; end += 1) {
      if (result[end] === "{") depth += 1;
      if (result[end] === "}") depth -= 1;
      if (depth === 0) break;
    }
    if (open < 0 || end >= result.length) throw new Error("Malformed legacy dark-mode media query");
    result = result.slice(0, start) + result.slice(end + 1);
  }
  return result;
}

