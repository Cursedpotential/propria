// Every OUR-OWN local module that (transitively) touches store.ts's
// module-level getStore() cache MUST be a real runtime import to the ONE
// shared dist file, never re-bundled/inlined per entry point. Each
// `await build()` below (bundle: true) otherwise inlines a local import
// (e.g. "./store.js") as its own private copy of that module's code —
// meaning its own private `cachedStore`. That is harmless for a remote ws://
// store (every copy just opens its own client connection to the same remote
// server) but actively wrong for the embedded engines: two independent opens
// of the same rocksdb:// PATH from one process can lock-conflict, and two
// independent opens of "mem://" are two DIFFERENT, mutually invisible
// in-memory databases — exactly the failure mode content-store.ts introduces
// the moment core.ts/court-language.ts/survival-guide.ts gained a
// (transitive) store.ts dependency.
//
// A plain string in esbuild's `external` array matches by import-specifier
// TEXT ONLY, with no awareness of which file wrote the import — and zod v4's
// own internal module tree contains files that ALSO import a relative
// "./core.js" (verified live: node_modules/zod/v4/core/errors.js). Naively
// externalizing "./core.js" broke that too, pointing zod's own internal
// import at our dist/core.js. This plugin instead externalizes a match ONLY
// when the importing file is one of OUR OWN src/*.ts files (never something
// under node_modules), so the two "./core.js"s never collide.
// Claude Code · Sonnet 5 · 2026-09-08.
const localModuleNames = ["store", "store-tools", "core", "court-language", "survival-guide", "content-store"];
function localExternalsPlugin() {
  const filter = new RegExp(`^\\./(${localModuleNames.join("|")})\\.js$`);
  return {
    name: "local-externals",
    setup(pluginBuild) {
      pluginBuild.onResolve({ filter }, (args) => {
        if (args.importer.includes(`${sep}node_modules${sep}`)) return null; // let esbuild resolve a third-party module of the same relative name normally
        return { path: args.path, external: true };
      });
    },
  };
}
